// Cached byte arrays for glyphs
const GLYPH_CACHE = new Map<number, Uint8Array>();

// Special glyphs
const RUPEE_CODE = 0x20B9; // ₹
const ARROW_LEFT_CODE = 0x2190; // ←
const ARROW_RIGHT_CODE = 0x2192; // →
const BULLET_CODE = 0x2022; // •
const CHECK_CODE = 0x2713; // ✓

// Hex representation of special glyphs
const SPECIAL_GLYPHS_HEX: Record<number, string> = {
  [RUPEE_CODE]: '00007e187e1878381c0e660000000000', // ₹ Indian Rupee Symbol
  [ARROW_LEFT_CODE]: '00000818387ff8381808000000000000', // ← Left Arrow
  [ARROW_RIGHT_CODE]: '000010181cff1f1c1810000000000000', // → Right Arrow
  [BULLET_CODE]: '000000183c3c18000000000000000000', // • Bullet
  [CHECK_CODE]: '00000003060c18706000000000000000', // ✓ Checkmark
};

function parseHexGlyph(hex: string): Uint8Array {
  const bytes = new Uint8Array(FONT_HEIGHT);
  for (let i = 0; i < FONT_HEIGHT; i++) {
    bytes[i] = parseInt(hex.substring(i * 2, i * 2 + 2), 16) || 0;
  }
  return bytes;
}

/**
 * Returns 16 bytes representing the 8x16 bitmap for a Unicode character code point.
 */
export function getGlyphBitmap(codePoint: number): Uint8Array {
  const cached = GLYPH_CACHE.get(codePoint);
  if (cached) return cached;

  let hex = FONT_DATA_HEX[codePoint];
  if (!hex && SPECIAL_GLYPHS_HEX[codePoint]) {
    hex = SPECIAL_GLYPHS_HEX[codePoint];
  }

  // Fallback for unknown unicode / non-latin: question mark or bullet
  if (!hex) {
    hex = FONT_DATA_HEX[63] || '00003c66060c18001800000000000000'; // ?
  }

  const bytes = parseHexGlyph(hex);
  GLYPH_CACHE.set(codePoint, bytes);
  return bytes;
}
